"""
Lot sale model — phase 1 of Lighthouse VRN: private lots, optional houses and the commons (the hybrid)
NS_Tokenomics / sim — v0.2, 2026-11-02

ALL INPUTS ARE PLACEHOLDERS. "What must be true" model, not a forecast, an offer or a price list.
Context and the rules this breaks: doc 31.

Reported, unconfirmed:
  * lots of about USD 15–40k, size unknown, assumed big enough for a family house (a call Gus has no record of);
  * Franz's USD 500k per family as a minimum (private call, 2026-11-02): in this model only the largest package gets there.
Everything else is Claude's estimate [criterio], with no quote behind it, for the team to replace.
No permaculture plan is being budgeted, so "300 reasons" (NS_permacultura 17) is NOT used here.

Run: python3 sim/lot_sale_sim.py > sim/RESULTS_lot_sale.md   (stdlib only)
"""

VERSION = "0.2"
DATE = "2026-11-02"

LOT_LOW, LOT_HIGH = 15_000, 40_000  # USD [NC, unrecorded call]
LOT_MID = (LOT_LOW + LOT_HIGH) / 2
M2_LOW, M2_HIGH = 1_344, 2_200      # lot sizes of the placeholder plan; the price runs linearly between them [criterio]
HOUSES = {                          # name: (m2, USD per m2) [criterio]; 170 m2 is Martín's reference house
    "Modular": (90, 1_000),
    "Family": (170, 1_400),
    "Large": (250, 2_000),
}
MIX = {"Lot only": 0.40, "Modular": 0.30, "Family": 0.20, "Large": 0.10}  # share of buyers [criterio]
HOUSE_MARGIN = 0.15        # share of the house price left after building it [criterio]
INFRA_PER_LOT = 12_000     # roads, water, power per lot [criterio]; no quote
OWNER_SHARE = 0.20         # share of the LOT price for the registered owner [criterio]; no deal yet
SELLING_COST = 0.04        # licensed broker, share of the price [criterio]; NetX can't take it (06 L32)
NETX_FEE = 0.03            # design and development CONTRACT, never a commission [verify] (06 L32; doc 30 §2)
CONTRIBUTION = 0.05        # one-off, share of the price paid, to the commons [criterio]
DUES = 1_200               # USD per lot per year [criterio]
BURN = 31_000              # USD per month, group burn (doc 12)
YEARS = 10
SALE_YEARS = 3             # lots sell evenly over these years [criterio]
FIRST_SECTOR_LOTS = 25     # placeholder sector, until Martín's KMZ arrives
TARGET_FAMILIES = 50       # [NC, Franz, call 2026-11-02]
FRANZ_PER_FAMILY = 500_000 # [NC, Franz, call 2026-11-02]
SCENARIOS = {"Slow": 10, "First sector": FIRST_SECTOR_LOTS, "Franz's target": TARGET_FAMILIES}
COMMONS_BUDGETS = (72_000, 240_000)  # USD per year: 72k is the opex of sim/RESULTS.md; 240k [criterio]
BASE_BUDGET = 72_000
# Founding Pass net commons capital, sim/RESULTS.md (assumes the cancelled Gathering; I-15). Needs Franz's OK.
TICKETS_NET = {"None": 0, "Low": 46_444, "Base": 161_375}


def lot_price(m2):
    """Linear between the two sizes, clamped to the reported range."""
    share = min(max((m2 - M2_LOW) / (M2_HIGH - M2_LOW), 0), 1)
    return LOT_LOW + share * (LOT_HIGH - LOT_LOW)


def house_price(name):
    m2, per_m2 = HOUSES[name]
    return m2 * per_m2


def package_price(name, lot=LOT_MID):
    return lot if name == "Lot only" else lot + house_price(name)


def average_package():
    return sum(share * package_price(name) for name, share in MIX.items())


def lot_margin(lot):
    """What a lot leaves after everything it has to pay for, before any house."""
    return lot * (1 - OWNER_SHARE - SELLING_COST - NETX_FEE - CONTRIBUTION) - INFRA_PER_LOT


def commons_balance(lots, dues, budget, tickets=0):
    """Commons balance per year. Returns (balances, first year it goes negative or None)."""
    balance = tickets
    sold = 0
    balances = []
    first_short = None
    for year in range(1, YEARS + 1):
        new = lots / SALE_YEARS if year <= SALE_YEARS else 0
        sold += new
        balance += new * average_package() * CONTRIBUTION + sold * dues - budget
        balances.append(balance)
        if balance < 0 and first_short is None:
            first_short = year
    return balances, first_short


def short(year):
    return "never in 10 years" if year is None else f"year {year}"


def main():
    print("# RESULTS — lot sale model (placeholders, not a forecast or an offer)\n")
    print(f"Generated by `sim/lot_sale_sim.py` v{VERSION}, {DATE}. Context and broken rules: doc 31. "
          "Lot prices are from an unrecorded call [NC]; every other input is a placeholder [criterio].\n")

    print("## 1. What people could buy\n")
    print("| Package | Lot (USD) | House (USD) | Price (USD) | Share of buyers |")
    print("|---|---:|---:|---:|---:|")
    for name, share in MIX.items():
        house = 0 if name == "Lot only" else house_price(name)
        print(f"| {name} | {LOT_MID:,.0f} | {house:,.0f} | {package_price(name):,.0f} | {share:.0%} |")
    print(f"\nAverage package: USD {average_package():,.0f}. Lots run from USD {LOT_LOW:,} to {LOT_HIGH:,}; the table uses the middle.\n")

    print("## 2. Does a lot pay for itself?\n")
    print(f"After owner {OWNER_SHARE:.0%}, broker {SELLING_COST:.0%}, NetX contract {NETX_FEE:.0%} [verify], "
          f"commons {CONTRIBUTION:.0%} and USD {INFRA_PER_LOT:,} of infrastructure.\n")
    print("| Lot price (USD) | Left after all that (USD) |")
    print("|---:|---:|")
    for lot in (LOT_LOW, LOT_MID, LOT_HIGH):
        print(f"| {lot:,.0f} | {lot_margin(lot):,.0f} |")
    breakeven = INFRA_PER_LOT / (1 - OWNER_SHARE - SELLING_COST - NETX_FEE - CONTRIBUTION)
    print(f"\nBreak-even lot price: USD {breakeven:,.0f}.\n")

    print("## 3. Totals by number of families\n")
    print("| Scenario | Families | Lots only (USD) | With the buyer mix (USD) | At Franz's USD 500k (USD) "
          "| Commons one-off, mix (USD) | NetX contract, mix [verify] (USD) | Months of burn |")
    print("|---|---:|---:|---:|---:|---:|---:|---:|")
    for name, n in SCENARIOS.items():
        mix = n * average_package()
        print(f"| {name} | {n} | {n * LOT_MID:,.0f} | {mix:,.0f} | {n * FRANZ_PER_FAMILY:,} | {mix * CONTRIBUTION:,.0f} "
              f"| {mix * NETX_FEE:,.0f} | {mix * NETX_FEE / BURN:.1f} |")

    print("\n## 4. Why private sale alone isn't enough\n")
    print(f"First sector ({FIRST_SECTOR_LOTS} families), buyer mix, contribution {CONTRIBUTION:.0%}, no yearly dues, "
          f"sales over {SALE_YEARS} years. The money comes once; the commons costs every year.\n")
    print("| Commons budget per year (USD) | Runs out | Balance in year 10 (USD) |")
    print("|---:|---|---:|")
    for budget in COMMONS_BUDGETS:
        balances, year = commons_balance(FIRST_SECTOR_LOTS, 0, budget)
        print(f"| {budget:,} | {short(year)} | {balances[-1]:,.0f} |")

    print("\n## 5. The hybrid: contribution + yearly dues + commons tickets\n")
    print(f"First sector, commons budget USD {BASE_BUDGET:,} a year.\n")
    print("| Dues per lot per year (USD) | Commons tickets, net (USD) | Runs out | Balance in year 10 (USD) |")
    print("|---:|---|---|---:|")
    for dues in (0, DUES, 3_000):
        for label, tickets in TICKETS_NET.items():
            balances, year = commons_balance(FIRST_SECTOR_LOTS, dues, BASE_BUDGET, tickets)
            print(f"| {dues:,} | {label} ({tickets:,}) | {short(year)} | {balances[-1]:,.0f} |")

    print("\n## 6. Dues that sustain the commons once sales stop\n")
    print("| Commons budget per year (USD) | " + " | ".join(f"{name} ({n})" for name, n in SCENARIOS.items()) + " |")
    print("|---:|" + "---:|" * len(SCENARIOS))
    for budget in COMMONS_BUDGETS:
        print(f"| {budget:,} | " + " | ".join(f"{budget / n:,.0f}" for n in SCENARIOS.values()) + " |")

    print("\n## Constants for lighthouse-platform\n")
    print("The platform reads these with this version, marked as sample values:\n")
    print(f"- `version`: {VERSION} ({DATE})")
    print(f"- `precioLoteMin`: {LOT_LOW} at {M2_LOW} m²; `precioLoteMax`: {LOT_HIGH} at {M2_HIGH} m² (linear between them)")
    for name, (m2, per_m2) in HOUSES.items():
        print(f"- `casa.{name}`: {m2} m² × USD {per_m2:,}/m² = USD {m2 * per_m2:,}")
    print(f"- `aporteUnico`: {CONTRIBUTION}")
    print(f"- `expensaAnual`: {DUES}")
    print(f"- `presupuestoComunAnual`: {BASE_BUDGET}")
    print(f"- `infraestructuraPorLote`: {INFRA_PER_LOT}")


if __name__ == "__main__":
    main()
