"""
Platform revenue model — what the Sumarte plans of lighthouse-platform could bring to NetX Gen
NS_Tokenomics / sim — v0.1, 2026-10-17

ALL INPUTS ARE ILLUSTRATIVE AND DELIBERATELY NOT OPTIMISTIC. "What must be true" model, not a forecast.

Prices come from lighthouse-platform `lib/sumarte/datos.ts` (mock-up v6 sample data, not approved prices):
  * Explorador: free
  * Miembro de la red: USD 10 / month or USD 100 / year
  * Plan Tribu: USD 60 / month per tribe
  * Pase Fundador: USD 300 / 1,500 / 5,000 (cohort of 300, minimum USD 75k)
The Founding Pass is NOT NetX revenue: its money goes to the commons (the Foundation; doc 25, doc 30).
It is shown separately so nobody counts it twice.

Run: python3 sim/platform_revenue_sim.py > sim/RESULTS_platform_revenue.md   (stdlib only)
"""

BURN = 31000            # USD per month, group burn (doc 12, from the financial model)
MONTHS = 36             # Nov 2026 -> Oct 2029
ANNUAL_SHARE = 0.6      # share of members paying yearly (USD 100) vs monthly (USD 10)
MEMBER_ARPU = ANNUAL_SHARE * 100 / 12 + (1 - ANNUAL_SHARE) * 10   # USD per paying member per month
TRIBE_PRICE = 60

SCENARIOS = {
    # registered users at the Feb 2027 Gathering, new users per month after, share paying, monthly churn
    # of paying members, tribes paying in month 12 / 24 / 36
    "Low": dict(start=300, growth=25, paying=0.03, churn=0.03, tribes=(2, 4, 6)),
    "Base (not optimistic)": dict(start=500, growth=60, paying=0.05, churn=0.025, tribes=(4, 8, 10)),
    "Good": dict(start=800, growth=120, paying=0.07, churn=0.02, tribes=(6, 12, 16)),
}

PASS_SCENARIOS = {
    # Founding Pass cohort (Feb 2027): passes sold by tier (Semilla 300, Brote 1,500, Raíz 5,000)
    "Low": (40, 15, 3),
    "Base (not optimistic)": (70, 30, 6),
    "Good": (120, 50, 12),
}


def tribes_at(m, t):
    if m <= 12:
        return round(t[0] * m / 12)
    if m <= 24:
        return round(t[0] + (t[1] - t[0]) * (m - 12) / 12)
    return round(t[1] + (t[2] - t[1]) * (m - 24) / 12)


def run(p):
    users = p["start"]
    paying = users * p["paying"]
    rows = []
    total = 0.0
    for m in range(1, MONTHS + 1):
        users += p["growth"]
        # new paying members come from new users; existing ones churn
        paying = paying * (1 - p["churn"]) + p["growth"] * p["paying"]
        rev = paying * MEMBER_ARPU + tribes_at(m, p["tribes"]) * TRIBE_PRICE
        total += rev
        rows.append((m, users, paying, tribes_at(m, p["tribes"]), rev))
    return rows, total


if __name__ == "__main__":
    print("# RESULTS — platform revenue from the Sumarte plans (illustrative, not a forecast)\n")
    print("Generated by `sim/platform_revenue_sim.py`. Prices: lighthouse-platform `lib/sumarte/datos.ts` "
          "(sample data). Group burn USD 31k/month (doc 12). Month 1 = Nov 2026.\n")
    print(f"Average revenue per paying member: USD {MEMBER_ARPU:.2f}/month "
          f"({ANNUAL_SHARE:.0%} pay yearly at USD 100, the rest monthly at USD 10).\n")
    print("## NetX revenue: memberships + Plan Tribu\n")
    print("| Scenario | Month | Registered users | Paying members | Tribes paying | Revenue / month (USD) | % of burn |")
    print("|---|---:|---:|---:|---:|---:|---:|")
    for name, p in SCENARIOS.items():
        rows, total = run(p)
        for m in (12, 24, 36):
            _, u, pay, tr, rev = rows[m - 1]
            print(f"| {name} | {m} | {u:,.0f} | {pay:,.0f} | {tr} | {rev:,.0f} | {rev / BURN:.1%} |")
    print()
    print("| Scenario | Total over 36 months (USD) | Months of burn it covers |")
    print("|---|---:|---:|")
    for name, p in SCENARIOS.items():
        _, total = run(p)
        print(f"| {name} | {total:,.0f} | {total / BURN:.1f} |")
    print("\n## Founding Pass (Feb 2027): money for the COMMONS, not for NetX\n")
    print("| Scenario | Semilla (300) | Brote (1,500) | Raíz (5,000) | Raised | vs minimum USD 75k |")
    print("|---|---:|---:|---:|---:|---|")
    for name, (s, b, r) in PASS_SCENARIOS.items():
        raised = s * 300 + b * 1500 + r * 5000
        print(f"| {name} | {s} | {b} | {r} | {raised:,} | {'reached' if raised >= 75000 else 'NOT reached'} |")
